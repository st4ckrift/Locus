
"""Hyprland keyboard shortcut integration for Locus."""

import os
import stat
import subprocess
import sys
from pathlib import Path
from typing import Any

from locus.config import validate_keybind


DEFAULT_HYPR_CONFIG = Path.home() / ".config" / "hypr"

DEFAULT_USER_KEYBINDS = (
    DEFAULT_HYPR_CONFIG
    / "UserConfigs"
    / "UserKeybinds.conf"
)

LOCUS_HYPR_CONFIG = DEFAULT_HYPR_CONFIG / "locus.conf"

SEARCH_COMMAND = "locus-search"

LEGACY_SOURCE_DIRECTIVE = "source = ~/.config/hypr/locus.conf"


def get_search_command() -> Path:
    """Resolve the Locus launcher from the active Python environment."""

    executable = (
        Path(sys.prefix)
        / "bin"
        / SEARCH_COMMAND
    )

    if not executable.is_file():
        raise FileNotFoundError(
            f"Locus search launcher not found: {executable}. "
            "Reinstall Locus with 'pip install -e .'"
        )

    if not os.access(executable, os.X_OK):
        raise PermissionError(
            f"Locus search launcher is not executable: {executable}"
        )

    return executable


def render_binding(
    keybind: dict[str, Any],
    search_command: Path | None = None,
) -> str:
    """Generate a Hyprland binding using an absolute launcher path."""

    validate_keybind(keybind)

    command = search_command or get_search_command()
    command = Path(command).expanduser().resolve()

    modifiers = " ".join(keybind["modifiers"])
    key = keybind["key"]

    return (
        f"bindd = {modifiers}, {key}, "
        f"Locus file search, exec, {command}"
    )


def _atomic_write(path: Path, content: str) -> None:
    """Atomically replace a file while preserving its permissions."""

    path.parent.mkdir(parents=True, exist_ok=True)

    original_mode = (
        stat.S_IMODE(path.stat().st_mode)
        if path.exists()
        else 0o644
    )

    temporary_path = path.with_name(
        f".{path.name}.locus.tmp"
    )

    try:
        with temporary_path.open(
            "w",
            encoding="utf-8",
        ) as file:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())

        temporary_path.chmod(original_mode)
        temporary_path.replace(path)

    finally:
        temporary_path.unlink(missing_ok=True)


def write_binding(
    keybind: dict[str, Any],
    output_path: Path = LOCUS_HYPR_CONFIG,
    search_command: Path | None = None,
) -> None:
    """Write the Locus-owned Hyprland configuration."""

    binding = render_binding(keybind, search_command)

    content = (
        "# Generated by Locus. Do not edit manually.\n"
        f"{binding}\n"
    )

    _atomic_write(output_path, content)


def ensure_source_directive(
    user_config: Path = DEFAULT_USER_KEYBINDS,
    source_config: Path = LOCUS_HYPR_CONFIG,
) -> bool:
    """Add or correct the Locus source directive.

    Existing user bindings are preserved.
    Returns True if the file was modified.
    """

    if not user_config.is_file():
        raise FileNotFoundError(
            "Hyprland user keybindings file not found: "
            f"{user_config}"
        )

    content = user_config.read_text(encoding="utf-8")
    lines = content.splitlines()

    expected_directive = (
        f"source = {Path(source_config).expanduser().resolve()}"
    )

    updated_lines = []
    found_directive = False
    modified = False

    for line in lines:
        stripped = line.strip()

        if stripped == LEGACY_SOURCE_DIRECTIVE:
            if not found_directive:
                updated_lines.append(expected_directive)
                found_directive = True
            modified = True
            continue

        if stripped == expected_directive:
            if not found_directive:
                updated_lines.append(line)
                found_directive = True
            else:
                modified = True
                continue
        else:
            updated_lines.append(line)

    if not found_directive:
        if updated_lines and updated_lines[-1] != "":
            updated_lines.append("")

        updated_lines.extend([
            "# Locus keyboard shortcut integration",
            expected_directive,
        ])
        modified = True

    if not modified:
        return False

    updated_content = "\n".join(updated_lines) + "\n"

    _atomic_write(user_config, updated_content)

    return True


def reload_hyprland() -> None:
    """Reload the current Hyprland configuration."""

    subprocess.run(
        ["hyprctl", "reload"],
        check=True,
        capture_output=True,
        text=True,
    )


def install_keybind(
    keybind: dict[str, Any],
    reload: bool = True,
) -> None:
    """Install or update the Locus-owned Hyprland shortcut."""

    write_binding(keybind)
    ensure_source_directive()

    if reload:
        reload_hyprland()

