
"""Hyprland keyboard shortcut integration for Locus."""

import subprocess
from pathlib import Path
from typing import Any

from locus.config import validate_keybind


DEFAULT_HYPR_CONFIG = (
    Path.home() / ".config" / "hypr"
)

DEFAULT_USER_KEYBINDS = (
    DEFAULT_HYPR_CONFIG
    / "UserConfigs"
    / "UserKeybinds.conf"
)

LOCUS_HYPR_CONFIG = (
    DEFAULT_HYPR_CONFIG / "locus.conf"
)

SOURCE_DIRECTIVE = "source = ~/.config/hypr/locus.conf"

SEARCH_COMMAND = "locus-search"


def render_binding(keybind: dict[str, Any]) -> str:
    """Generate a Hyprland binding from Locus shortcut settings."""

    validate_keybind(keybind)

    modifiers = " ".join(keybind["modifiers"])
    key = keybind["key"]

    return (
        f"bindd = {modifiers}, {key}, "
        f"Locus file search, exec, {SEARCH_COMMAND}"
    )


def write_binding(
    keybind: dict[str, Any],
    output_path: Path = LOCUS_HYPR_CONFIG,
) -> None:
    """Write the Locus-owned Hyprland configuration."""

    binding = render_binding(keybind)

    output_path.parent.mkdir(parents=True, exist_ok=True)

    temporary_path = output_path.with_name(
        f".{output_path.name}.tmp"
    )

    try:
        temporary_path.write_text(
            "# Generated by Locus. Do not edit manually.\n"
            f"{binding}\n",
            encoding="utf-8",
        )

        temporary_path.replace(output_path)

    finally:
        temporary_path.unlink(missing_ok=True)


def ensure_source_directive(
    user_config: Path = DEFAULT_USER_KEYBINDS,
) -> bool:
    """Add the Locus configuration source if it is absent.

    Returns True if the file was modified.
    """

    if not user_config.is_file():
        raise FileNotFoundError(
            f"Hyprland user keybindings file not found: {user_config}"
        )

    content = user_config.read_text(encoding="utf-8")

    if SOURCE_DIRECTIVE in content.splitlines():
        return False

    updated = content

    if updated and not updated.endswith("\n"):
        updated += "\n"

    updated += (
        "\n# Locus keyboard shortcut integration\n"
        f"{SOURCE_DIRECTIVE}\n"
    )

    temporary_path = user_config.with_name(
        f".{user_config.name}.locus.tmp"
    )

    try:
        temporary_path.write_text(
            updated,
            encoding="utf-8",
        )
        temporary_path.replace(user_config)

    finally:
        temporary_path.unlink(missing_ok=True)

    return True


def reload_hyprland() -> None:
    """Reload the current Hyprland configuration."""

    subprocess.run(
        ["hyprctl", "reload"],
        check=True,
        capture_output=True,
        text=True,
    )


def install_keybind(
    keybind: dict[str, Any],
    reload: bool = True,
) -> None:
    """Install or update the Locus-owned Hyprland shortcut."""

    write_binding(keybind)
    ensure_source_directive()

    if reload:
        reload_hyprland()

